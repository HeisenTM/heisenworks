#!/usr/bin/env python3
"""Scans the folders inside /works and writes works/manifest.js (the site reads this file).
Run:  python3 update-works.py      (GitHub does this for you automatically on every upload)"""
import json, os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'works')
IMG = {'.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif', '.svg'}
VID = {'.mp4', '.webm', '.mov', '.m4v'}

def natural(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r'(\d+)', s)]

def ext(f):
    return os.path.splitext(f)[1].lower()

def stem(f):
    return os.path.splitext(f)[0].lower()

out = {}
for folder in sorted(os.listdir(ROOT)):
    path = os.path.join(ROOT, folder)
    if not os.path.isdir(path):
        continue
    files = sorted((f for f in os.listdir(path) if not f.startswith('.')), key=natural)
    if folder == 'video-edits':
        posters = {stem(f): f for f in files if ext(f) in IMG}
        out[folder] = [
            {'file': f, **({'poster': posters[stem(f)]} if stem(f) in posters else {})}
            for f in files if ext(f) in VID
        ]
    else:
        out[folder] = [f for f in files if ext(f) in IMG | VID]

with open(os.path.join(ROOT, 'manifest.js'), 'w', encoding='utf-8') as fh:
    fh.write('// Auto-generated by update-works.py. Do not edit by hand.\n')
    fh.write('window.WORKS_MANIFEST = ' + json.dumps(out, indent=1, ensure_ascii=False) + ';\n')
print({k: len(v) for k, v in out.items()})
